"""Release-only ASGI adapter; permits empty identity settings in fixture mode."""
import os
from pathlib import Path

from app.config import Settings
from app.store import SQLiteStore


def deployment_settings():
    if os.environ.get('QWENNOTE_SOURCE', 'http').strip() != 'fixture':
        return Settings.from_env()
    # No invented credentials or administrator identity. Core settings still validate.
    for key in ('DB_PATH', 'FEISHU_REDIRECT_URI', 'SESSION_SECRET', 'QWENNOTE_FIXTURE_DIR'):
        if not os.environ.get(key, '').strip():
            raise ValueError('Missing environment variables: ' + key)
    return Settings(
        feishu_app_id=os.environ.get('FEISHU_APP_ID', '').strip(),
        feishu_app_secret=os.environ.get('FEISHU_APP_SECRET', '').strip(),
        feishu_redirect_uri=os.environ['FEISHU_REDIRECT_URI'].strip(),
        session_secret=os.environ['SESSION_SECRET'].strip(),
        db_path=Path(os.environ['DB_PATH']).expanduser(),
        admin_open_id=os.environ.get('ADMIN_OPEN_ID', '').strip(),
        minutes_source='fixture',
        minutes_fixture_dir=Path(os.environ['QWENNOTE_FIXTURE_DIR']).expanduser(),
        backfill_days=int(os.environ.get('BACKFILL_DAYS', '90')),
    )


class DeploymentStore(SQLiteStore):
    def seed_admin(self, open_id):
        if open_id:
            super().seed_admin(open_id)


def build_app(factory):
    settings = deployment_settings()
    return factory(settings=settings, store=DeploymentStore(settings.db_path))


def prepare_release(release):
    """Generate app.main:app inside an extracted release, never in the checkout."""
    main = Path(release) / 'app/main.py'
    marker = '# Generated by qwennote deployment'
    if marker not in main.read_text():
        with main.open('a') as output:
            output.write('\n\n' + marker + '\n'
                         'from scripts.deployment_runtime import build_app as _build_deployed_app\n'
                         'app = _build_deployed_app(create_app)\n')


if __name__ == '__main__':
    import sys
    prepare_release(sys.argv[1])
